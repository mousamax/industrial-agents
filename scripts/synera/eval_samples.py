"""Write docs/synera/EVAL_SAMPLES.md: real questions, tool calls and replies from the latest scoreboard runs,
one per kind and suite, plus a few scenario transcripts. For reading and reasoning about the agent.

The holdout suite is left out on purpose: it is only ever scored, never read.

    uv run python scripts/synera/eval_samples.py
"""

from __future__ import annotations

import json
import random

from app.agents.building_guide.bench import DATASET_FILES, DATASETS, REPORTS, load_questions
from app.settings import ROOT

OUT = ROOT / "docs" / "synera" / "EVAL_SAMPLES.md"
SUITES = {
    "benchmark": "Synera's scored kinds, as they send them",
    "warmup": "Sunday-style find and route questions (Answer instruction added by us)",
    "reworded": "Scored kinds rewritten in other styles",
    "unseen": "New kinds Synera hasn't shown, answers computed by our code (dev buildings)",
}


def short_args(args: dict) -> str:
    return ", ".join(f"{k}={json.dumps(v, ensure_ascii=False)}" for k, v in args.items())


def questions(suite: str) -> dict[str, dict]:
    if suite in DATASET_FILES:
        path = DATASETS / DATASET_FILES[suite].format(split="dev")
        return {q["id"]: q for q in map(json.loads, path.read_text(encoding="utf-8").splitlines())}
    return {q["id"]: q for q in load_questions("dev", None, None, suite)}


def main() -> None:
    rng = random.Random(3)
    out = [
        "# Eval samples",
        "",
        "Generated by `scripts/synera/eval_samples.py` from the latest scoreboard runs. One",
        "question per kind and suite (a failing one when there is one), then three scenario transcripts.",
        "",
    ]
    for suite, what in SUITES.items():
        path = REPORTS / f"bench-scoreboard-{suite}.jsonl"
        if not path.exists():
            continue
        results, qs = (
            [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines()],
            questions(suite),
        )
        out += [f"## {suite}: {what}", ""]
        for kind in sorted({r["kind"] for r in results}):
            mine = [r for r in results if r["kind"] == kind]
            r = next((x for x in mine if not x["ok"]), rng.choice(mine))
            q = qs.get(r["id"], {})
            out += [
                f"### {'✅' if r['ok'] else '❌'} {kind} · `{r['id']}`",
                "",
                f"> {q.get('question', '?')}",
                "",
            ]
            if "original" in q:
                out += [f"Original: _{q['original']}_", ""]
            out += [
                "Tools: "
                + (" → ".join(f"`{c['tool']}({short_args(c['args'])})`" for c in r["tool_calls"]) or "none"),
                "",
            ]
            out += ["```text", r["reply"].strip()[-900:], "```", ""]
            if not r["ok"]:
                out += [f"Expected: `{json.dumps(q.get('answer'), ensure_ascii=False)[:300]}`", ""]
    path = REPORTS / "scenarios-scoreboard.jsonl"
    if path.exists():
        scenarios = [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines()]
        out += ["## Scenarios: tricky users, judged on Synera's rubric", ""]
        for s in [
            x for x in scenarios if x["name"] in ("vague-press", "lift-closed-mid-conversation", "add-a-door")
        ]:
            out += [f"### {'✅' if s['ok'] else '❌'} {s['name']} (judges {s.get('judges_passed', '?')})", ""]
            for t in s["turns"]:
                tools = (
                    " → ".join(f"`{c['tool']}({short_args(c['args'])})`" for c in t["tool_calls"]) or "none"
                )
                out += [
                    f"**User:** {t['user']}",
                    "",
                    f"Tools: {tools}",
                    "",
                    "```text",
                    t["reply"].strip(),
                    "```",
                    "",
                ]
            out += [f"Judge: _{s['verdict']['summary']}_", ""]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
